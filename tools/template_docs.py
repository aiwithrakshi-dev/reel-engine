#!/usr/bin/env python3
"""Write templates/temp-N/TEMPLATE.md + templates/README.md from engine/templates.py (the single source of truth)."""
import os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..')); sys.path.insert(0, os.path.join(ROOT, 'engine'))
from templates import TEMPLATES, SAFE
GRID = f"""## Alignment grid (all templates)
```
x: 0 ─ 65 ───────────── safe box ───────────── 960 ─ 1080   (6 columns, 20 px gutter, centre line x = 512)
y 0-270      Instagram top UI          → nothing readable
y 280-430    HEAD band                 → labels / headlines (above the cap)
y cap..chin  FACE band                 → nothing on the face oval (FaceZone + 24 px margin)
y chin+40..1245 CAPTION band           → captions, pills, chips (max 30 chars per line)
y 1250-1920  Instagram bottom UI       → nothing readable
```
Safe box {SAFE}. Every readable box is checked by the renderer (`Reel.check`): leaving the box or touching the face stops the render.
Pace: captions appear on the word's start frame (never early); one visual event every 0.3-0.6 s; every scene change has an SFX.
"""
os.makedirs(f'{ROOT}/templates', exist_ok=True); idx = ['# Reel templates — `/temp-1` … `/temp-16`', '',
       'Pick a template with `/temp-N` (Claude skill `aiwithrakshith-reel-templates`) or `--template N` in a job file. '
       'Specs live in `engine/templates.py`; this folder is generated by `tools/template_docs.py`.', '',
       '| /temp | name | reference | best for | energy | hook | demo |', '|---|---|---|---|---|---|---|']
for n, t in TEMPLATES.items():
    d = f'{ROOT}/templates/temp-{n}'; os.makedirs(d, exist_ok=True)
    md = [f"# /temp-{n} — {t['name']}", '', f"**Reference:** {t['ref']}  ·  **Best for:** {t['best_for']}  ·  **Energy:** {t['energy']}", '',
          '## Look', t['look'], '', '## Spec', '| part | value |', '|---|---|']
    for k in ('grade', 'fonts', 'palette', 'headline', 'captions'):
        md.append(f"| {k} | {', '.join(f'{a}: {b}' for a, b in t[k].items()) if isinstance(t[k], dict) else t[k]} |")
    md += [f"| scenes | {'; '.join(t['scenes'])} |", f"| transitions | {', '.join(t['transitions'])} |", f"| hook | {t['hook']} |",
           f"| pace | {t['pace']} |", f"| music | {t['music']} |", f"| renderer | `{t['renderer']}` |", '', GRID,
           '## Job file', '```json', '{"template": %d, "aroll": "aroll_tight30.mp4", "dy": 60, "duration": 15.5,' % n,
           ' "face": {"cap_top": 505, "chin": 1100, "x0": 330, "x1": 750}, "words": "words_reel.json",',
           ' "headlines": [{"label": "claude and codex inside", "big": "ANDROID STUDIO", "label_t": 0.0, "big_t": 2.26}],',
           ' "scenes": [{"t0": 2.15, "t1": 6.12, "title": "...", "image": "shot.png"}], "hook": "%s", "vo": "vo.wav", "music": "bed.mp3"}' % (t['hook'].split()[0] if n > 1 else 'pixel_assemble'),
           '```', f'Demo: `examples/templates_demo/jobs/temp-{n}.json` → `samples/templates/temp-{n}.mp4`.']
    open(f'{d}/TEMPLATE.md', 'w').write('\n'.join(md) + '\n')
    idx.append(f"| [/temp-{n}](temp-{n}/TEMPLATE.md) | {t['name']} | {t['ref']} | {t['best_for']} | {t['energy']} | {t['hook']} | `samples/templates/temp-{n}_preview.mp4` |")
idx += ['', '![templates 1-7](../docs/images/templates_strip.jpg)', '', '![templates 8-16](../docs/images/templates_strip_2.jpg)', '', GRID]
open(f'{ROOT}/templates/README.md', 'w').write('\n'.join(idx) + '\n'); print('templates docs written')
